// Writes the site's icons from the orb (run from the repo root): node brand/color/make-site-icons.mjs
//   src/app/favicon.ico (16+32+48), src/app/icon.png (512, transparent), src/app/apple-icon.png (180, white),
//   public/logo.png (512, orb on white: schema.org Organization.logo), src/app/og/orb.ts (the /og mark).
import sharp from "sharp"
import { writeFile } from "fs/promises"
import { orbSvg } from "./orb.mjs"

const png = (o, size) => sharp(Buffer.from(orbSvg({ size, ...o }))).png().toBuffer()
function ico(images) {
  const head = Buffer.alloc(6); head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(images.length, 4)
  const dir = [], data = []
  let off = 6 + 16 * images.length
  for (const { size, buf } of images) {
    const e = Buffer.alloc(16)
    e.writeUInt8(size >= 256 ? 0 : size, 0); e.writeUInt8(size >= 256 ? 0 : size, 1); e.writeUInt8(0, 2); e.writeUInt8(0, 3)
    e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6); e.writeUInt32LE(buf.length, 8); e.writeUInt32LE(off, 12)
    dir.push(e); data.push(buf); off += buf.length
  }
  return Buffer.concat([head, ...dir, ...data])
}
const fav = []
for (const size of [16, 32, 48]) fav.push({ size, buf: await png({ scale: 0.94 }, size) })
await writeFile("src/app/favicon.ico", ico(fav))
await writeFile("src/app/icon.png", await png({ scale: 0.94 }, 512))
await writeFile("src/app/apple-icon.png", await sharp(Buffer.from(orbSvg({ size: 180, bg: "#ffffff", scale: 0.72 }))).flatten({ background: "#ffffff" }).png().toBuffer())
await writeFile("public/logo.png", await png({ bg: "#ffffff", scale: 0.72 }, 512))
const og = await sharp(Buffer.from(orbSvg({ size: 88 }))).png({ palette: true, colors: 256, effort: 10 }).toBuffer()
await writeFile("src/app/og/orb.ts", `// Generated by brand/color/make-site-icons.mjs: the orb mark (88px PNG) for the /og card.\nexport const ORB_PNG = "data:image/png;base64,${og.toString("base64")}"\n`)
console.log("site icons ok")
